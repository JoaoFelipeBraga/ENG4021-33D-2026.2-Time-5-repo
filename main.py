def soma():
    a = float(input("Primeiro número: "))
    b = float(input("Segundo número: "))
    print(f"Resultado: {a + b}")


def multiplicacao():
    a = float(input("Primeiro número: "))
    b = float(input("Segundo número: "))
    print(f"Resultado: {a * b}")

def exponenciacao( x, y):
    return x ** y

def percentual(x, y):
    return (x * y) / 100    
